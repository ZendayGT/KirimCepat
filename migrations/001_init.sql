CREATE TABLE IF NOT EXISTS tarif_zona (
  zona VARCHAR(20) PRIMARY KEY,
  tarif_per_kg INT NOT NULL
);

CREATE TABLE IF NOT EXISTS resi_counter (
  tanggal DATE PRIMARY KEY,
  terakhir INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS shipments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  resi VARCHAR(20) NOT NULL UNIQUE,
  pengirim VARCHAR(100) NOT NULL,
  penerima VARCHAR(100) NOT NULL,
  alamat_tujuan VARCHAR(255) NOT NULL,
  zona VARCHAR(20) NOT NULL,
  berat_kg DECIMAL(8,2) NOT NULL,
  panjang_cm DECIMAL(8,2) NOT NULL DEFAULT 0,
  lebar_cm DECIMAL(8,2) NOT NULL DEFAULT 0,
  tinggi_cm DECIMAL(8,2) NOT NULL DEFAULT 0,
  ongkir INT NOT NULL,
  status ENUM('DIBUAT','DIJEMPUT','TRANSIT','DIANTAR','DITERIMA')
    NOT NULL DEFAULT 'DIBUAT',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (zona) REFERENCES tarif_zona(zona)
);

CREATE TABLE IF NOT EXISTS status_history (
  id INT AUTO_INCREMENT PRIMARY KEY,
  shipment_id INT NOT NULL,
  status ENUM('DIBUAT','DIJEMPUT','TRANSIT','DIANTAR','DITERIMA') NOT NULL,
  catatan VARCHAR(255),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (shipment_id) REFERENCES shipments(id)
);